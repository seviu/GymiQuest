const copies: Record<LearningLocale, ArchiveCopy> = { en: english, it: italian, es: spanish, de: german }

export function archiveCopy(locale: LearningLocale): ArchiveCopy {
  return copies[locale]
}

export function archiveDocumentKindLabels(locale: LearningLocale): Record<OfficialArchiveDocumentKind, string> {
  return archiveCopy(locale).documentKinds
}

export function archiveReviewChoices(locale: LearningLocale): ReadonlyArray<{
  status: ArchivePracticeReviewStatus
  label: string
  detail: string
}> {
  const choices = archiveCopy(locale).practice.choices
  return (["answer-matches", "answer-differs-or-unclear", "not-attempted"] as const).map((status) => ({
    status,
    ...choices[status],
  }))
}
