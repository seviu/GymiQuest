const messageCatalogs: Record<LearningLocale, MessageCatalog> = {
  en: englishMessages,
  it: italianMessages,
  es: spanishMessages,
  de: germanMessages,
}

export function translateMessage(
  locale: LearningLocale,
  key: MessageKey,
  values: MessageValues = {},
): string {
  const template = messageCatalogs[locale][key]
  return template.replace(/\{([a-zA-Z][a-zA-Z0-9]*)\}/gu, (match, name: string) => (
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : match
  ))
}

export function messageCatalog(locale: LearningLocale): MessageCatalog {
  return messageCatalogs[locale]
}
