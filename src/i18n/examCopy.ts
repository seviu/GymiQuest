const copies: Record<LearningLocale, ExamCopy> = { en: english, it: italian, es: spanish, de: german }

export function examCopy(locale: LearningLocale): ExamCopy {
  return copies[locale]
}

export function examWarning(locale: LearningLocale, seconds: number): string | undefined {
  const warning = examCopy(locale).warning
  if (seconds <= 60) return warning.oneMinute
  if (seconds <= 5 * 60) return warning.fiveMinutes
  if (seconds <= 10 * 60) return warning.tenMinutes
  if (seconds <= 30 * 60) return warning.thirtyMinutes
  return undefined
}

export function submissionEyebrow(
  locale: LearningLocale,
  reason: MockSubmissionReason,
  official: boolean,
): string {
  const copy = examCopy(locale)
  if (reason === "timeout") return official ? copy.officialResults.timedOut : copy.generatedResults.timedOut
  return official ? copy.officialResults.submitted : copy.generatedResults.submitted
}
